export function getTeamData(name: string): TeamInfo | undefined {
  if (TEAMS_DATA[name]) return TEAMS_DATA[name];
  const lower = name.toLowerCase().trim();
  if (TEAM_ALIASES[lower] && TEAMS_DATA[TEAM_ALIASES[lower]]) {
    return TEAMS_DATA[TEAM_ALIASES[lower]];
  }
  const foundKey = Object.keys(TEAMS_DATA).find(k => k.toLowerCase() === lower);
  if (foundKey) return TEAMS_DATA[foundKey];
  return undefined;
}

